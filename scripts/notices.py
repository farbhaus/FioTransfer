#!/usr/bin/env python3
"""Print the licenses of everything third-party in FioTransfer: the Rust crates
compiled into the app and the CLI, and the Inter font. Their licenses require
these notices to ship with the app.

    scripts/notices.py > THIRD_PARTY_NOTICES.txt
    scripts/notices.py --check     # exit 1 when THIRD_PARTY_NOTICES.txt is stale

Crates come from `cargo metadata`: everything the workspace's packages depend on
as normal dependencies, on any platform, minus proc-macros (they run in the
compiler and ship nothing). Where a crate offers a choice ("MIT OR Apache-2.0")
the first of PREFER is the one used and reproduced. A crate that publishes no
license file gets its license's standard text, with its authors as the
copyright holders. Crates with the same texts share one section.
"""

from __future__ import annotations

