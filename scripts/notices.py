def cargo_metadata() -> dict:
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


def shipped(meta: dict) -> list[dict]:
    """Every crate the workspace links in, on any platform."""
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    members = set(meta["workspace_members"])
    seen: set[str] = set()
    stack = list(members)
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    crates = [packages[p] for p in seen - members]
    crates = [c for c in crates if not any("proc-macro" in t["kind"] for t in c["targets"])]
    return sorted(crates, key=lambda c: (c["name"], c["version"]))


def split_top(expr: str, op: str) -> list[str]:
    """Splits an SPDX expression on `op` outside parentheses."""
    parts, depth, cur = [], 0, ""
    tokens = re.split(r"(\(|\)|\s+)", expr)
    for tok in tokens:
        if tok == "(":
            depth += 1
        elif tok == ")":
            depth -= 1
        if depth == 0 and tok == op:
            parts.append(cur.strip())
            cur = ""
        else:
            cur += tok
    parts.append(cur.strip())
    return [p for p in parts if p]


def unwrap(term: str) -> str:
    term = term.strip()
    while term.startswith("(") and term.endswith(")"):
        term = term[1:-1].strip()
    return term


def choose(expr: str) -> list[str]:
    """The licenses used: one per AND term, the preferred option of each OR."""
    expr = expr.replace("/", " OR ")
    chosen = []
    for term in split_top(unwrap(expr), "AND"):
        options = [unwrap(o) for o in split_top(unwrap(term), "OR")]
        chosen.append(min(options, key=lambda o: PREFER.index(o) if o in PREFER else len(PREFER)))
    return chosen


def kind_of(name: str, text: str) -> str | None:
    n = name.upper()
    for key, kind in [
        ("MIT", "MIT"), ("APACHE", "Apache-2.0"), ("BSD", "BSD"), ("ZLIB", "Zlib"),
        ("UNLICENSE", "Unlicense"), ("OFL", "OFL-1.1"), ("UFL", "Ubuntu-font-1.0"),
        ("BOOST", "BSL-1.0"), ("BSL", "BSL-1.0"), ("CC0", "CC0-1.0"), ("UNICODE", "Unicode"),
    ]:
        if key in n:
            return kind
    if n.startswith("NOTICE"):
        return "NOTICE"
    upper = text.upper()
    for needle, kind in [
        ("PERMISSION IS HEREBY GRANTED, FREE OF CHARGE", "MIT"),
        ("APACHE LICENSE", "Apache-2.0"),
        ("REDISTRIBUTION AND USE IN SOURCE AND BINARY FORMS", "BSD"),
        ("THIS IS FREE AND UNENCUMBERED SOFTWARE", "Unlicense"),
        ("PERMISSION TO USE, COPY, MODIFY, AND", "ISC"),
        ("THIS SOFTWARE IS PROVIDED 'AS-IS'", "Zlib"),
        ("BOOST SOFTWARE LICENSE", "BSL-1.0"),
        ("UNICODE", "Unicode"),
        ("COMMUNITY DATA LICENSE AGREEMENT", "CDLA"),
        ("MOZILLA PUBLIC LICENSE", "MPL-2.0"),
        ("SIL OPEN FONT LICENSE", "OFL-1.1"),
        ("UBUNTU FONT LICENCE", "Ubuntu-font-1.0"),
        ("CREATIVE COMMONS", "CC0-1.0"),
    ]:
        if needle in upper:
            return kind
    return None


def generic(name: str) -> bool:
    """LICENSE, LICENSE.md, COPYING… — a name that doesn't say which license."""
    stem = re.sub(r"\.(txt|md|markdown)$", "", name, flags=re.I).upper()
    return stem in ("LICENSE", "LICENCE", "COPYING", "COPYRIGHT")


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace").strip("\n")


def holders(crate: dict) -> str:
    names = [re.sub(r"\s*<[^>]*>", "", a).strip() for a in crate.get("authors") or []]
    names = [n for n in names if n]
    return ", ".join(names) if names else f"the {crate['name']} authors"


def texts(crate: dict, apache: str) -> list[str]:
    """The license texts reproduced for a crate."""
    root = Path(crate["manifest_path"]).parent
    expr = crate.get("license") or ""
    chosen = choose(expr) if expr else []
    want = {FAMILY.get(c, c) for c in chosen}

    files = sorted(f for f in root.iterdir() if f.is_file() and LICENSE_FILE.match(f.name))
    if crate.get("license_file"):
        lf = root / crate["license_file"]
        if lf.is_file() and lf not in files:
            files.append(lf)
    # Bundled fonts and the like keep their licenses next to them.
    extra = [f for d in ("fonts", "licenses", "LICENSES") if (root / d).is_dir()
             for f in sorted((root / d).iterdir()) if f.suffix in (".txt", ".md")]

    picked, covered = [], set()
    for f in files:
        kind = kind_of(f.name, read(f))
        if generic(f.name):
            # A plain LICENSE or COPYING is the author's own account of the
            # crate's licensing (often several licenses in one file): kept whole.
            picked.append(f)
            covered |= want
        elif kind == "NOTICE" or not want or kind in want:
            picked.append(f)
            covered.add(kind)
    if files and not picked:
        picked = files  # nothing recognisable: reproduce them all
        covered = want
    for f in extra:
        kind = kind_of(f.name, read(f))
        picked.append(f)
        if kind in ("OFL-1.1", "Ubuntu-font-1.0"):
            covered.add(kind)

    out = [read(f) for f in picked]
    for lic in want - covered:
        if lic == "MIT":
            out.insert(0, f"Copyright (c) {holders(crate)}\n\n{MIT_TEXT}")
        elif lic == "Zlib":
            out.insert(0, f"Copyright (c) {holders(crate)}\n\n{ZLIB_TEXT}")
        elif lic == "BSL-1.0":
            out.insert(0, BSL_TEXT)
        elif lic == "CC0-1.0":
            out.insert(0, CC0_TEXT)
        elif lic == "Apache-2.0" and apache:
            out.insert(0, f"Copyright (c) {holders(crate)}\n\n{apache}")
        else:
            raise SystemExit(f"notices: {crate['name']} {crate['version']}: no text for {lic}")
    return out


def apache_text(crates: list[dict]) -> str:
    """The Apache 2.0 text, from a crate that ships it."""
    for c in crates:
        root = Path(c["manifest_path"]).parent
        for f in sorted(root.iterdir()):
            if f.is_file() and "APACHE" in f.name.upper():
                return read(f)
    return ""


def render() -> str:
    crates = shipped(cargo_metadata())
    apache = apache_text(crates)
    groups: dict[tuple[str, ...], list[dict]] = {}
    for c in crates:
        groups.setdefault(tuple(texts(c, apache)), []).append(c)

    lines = [
        "FioTransfer includes the third-party software below. Each part is covered",
        "by its own license, reproduced here. Where a part offers a choice of",
        "licenses, the one reproduced is the one FioTransfer uses.",
    ]

    def section(title: list[str], body: list[str]) -> None:
        lines.extend(["", RULE, *title, RULE, ""])
        lines.append("\n\n".join(body))

    for body, members in sorted(groups.items(), key=lambda g: (g[1][0]["name"], g[1][0]["version"])):
        title = []
        for c in members:
            repo = c.get("repository") or c.get("homepage") or ""
            title.append(f"{c['name']} {c['version']}" + (f" ({repo})" if repo else ""))
        section(title, list(body))

    section(["Inter font (https://github.com/rsms/inter)"], [read(ROOT / "egui-ui" / "assets" / "OFL.txt")])
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print("THIRD_PARTY_NOTICES.txt is out of date; run scripts/notices.py > THIRD_PARTY_NOTICES.txt", file=sys.stderr)
            return 1
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    os.environ.setdefault("CARGO_TERM_COLOR", "never")
    raise SystemExit(main())
